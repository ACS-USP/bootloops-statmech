"""The row-to-row transfer matrix of the width-L Ising strip, built and diagonalised directly
(numpy, double precision): an independent numerical route for the strip gaps of
lattice/correlation2d.py (Onsager's spectrum), sharing no code with it.

Strip: L spins per row, J = 1, K = beta, periodic across (the cylinder), rows coupled site by site.
Symmetric form T[s, s'] = exp(K (e(s) + e(s'))/2 + K sum_i s_i s'_i), e(s) the row's own bond sum.
Its eigenvalues are the lambda's of the strip (the normalisation cancels in ratios); the matrix is
built as e^{-2LK} T (exponents <= 0: no overflow at any beta; at large beta the subleading
eigenvalues fall below double-precision resolution, which the caller must judge).

Symmetry sectors.  The group G generated by the row translations (periodic boundary only) acts on
configurations; with the spin flip F, a G-orbit O with representative r_O spans one normalised
state per character chi of F (+1: principal / even sector, -1: odd sector; an orbit containing
F r_O carries no odd state), and
  <O| T |O'> = sqrt(|O| / |O'|) sum_{s' in O'} chi(s') T[r_O, s']
(|O| counts the configurations of O together with their flips).  For the periodic strip this is
the zero-momentum sector, which holds lambda_0 (even), lambda_1 (odd) and lambda_2 (even: the pair
of momenta +-pi/L).  Eigenvalues by numpy.linalg.eigh; values are floats, not certified.

  strip_spectrum(L, beta) -> (gap_odd, gap_even)   ln(lambda_0/lambda_1), ln(lambda_0/lambda_2)
  strip_correlations(L, beta) -> (nn_row, nn_col, diag)   on the infinite cylinder, from the
      principal eigenvector psi of the dense T:  <s_{0,0} s_{0,1}> = sum psi^2 s_0 s_1,
      <s_{0,0} s_{1,0}> = psi s_0 T s_0 psi / lambda_0,  <s_{0,0} s_{1,1}> = psi s_0 T s_1 psi / lambda_0
L <= 10 (1024 states); strip_correlations builds the dense 2^L x 2^L matrix.
_HOOKS["boundary"] ("periodic"; planted "open": no bond across the seam, no translations).
"""
import math

from ..core import Refusal
from .coupling import coupling

_HOOKS = {"boundary": "periodic"}
MAX_L = 10


def _K(beta):
    c = coupling(beta)
    if c.kind == "critical":
        return math.log(1 + math.sqrt(2)) / 2
    if c.kind == "x":
        return -math.log(c.x) / 2
    return float(c.K)


def _check(L, beta):
    if isinstance(L, bool) or not isinstance(L, int) or not 2 <= L <= MAX_L:
        raise Refusal("precondition:size", f"L = {L!r}: need an int in 2 .. {MAX_L}")
    return _K(beta)


def _row_bonds(L, s):
    periodic = _HOOKS["boundary"] == "periodic"
    spins = [1 - 2 * ((s >> i) & 1) for i in range(L)]
    return sum(spins[i] * spins[i + 1] for i in range(L - 1)) + (spins[-1] * spins[0] if periodic else 0)


def _orbits(L):
    mask = (1 << L) - 1
    shifts = range(L) if _HOOKS["boundary"] == "periodic" else range(1)
    rot = lambda s, k: ((s << k) | (s >> (L - k))) & mask if k else s
    seen, out = set(), []
    for s in range(1 << L):
        if s in seen:
            continue
        orb = {}
        for k in shifts:
            t = rot(s, k)
            orb[t] = 1
        flips = {t ^ mask for t in orb}
        odd_ok = not (flips & set(orb))
        for t in flips:
            orb.setdefault(t, -1)
        seen |= set(orb)
        out.append((s, orb, odd_ok))
    return out


def _sector(L, K, chi):
    import numpy as np
    orbs = [o for o in _orbits(L) if chi == 1 or o[2]]
    e = [_row_bonds(L, s) for s in range(1 << L)]
    M = np.zeros((len(orbs), len(orbs)))
    for a, (r, orb, _) in enumerate(orbs):
        for b, (_, orb2, _) in enumerate(orbs):
            acc = 0.0
            for s2, ch in orb2.items():
                m = (e[r] + e[s2]) / 2 + L - 2 * bin(r ^ s2).count("1")
                acc += (ch if chi == -1 else 1) * math.exp(K * (m - 2 * L))   # m <= 2L
            M[a, b] = acc * math.sqrt(len(orb) / len(orb2))
    return M


def strip_spectrum(L, beta):
    import numpy as np
    K = _check(L, beta)
    ev = np.linalg.eigvalsh(_sector(L, K, 1))
    od = np.linalg.eigvalsh(_sector(L, K, -1))
    l0, l2, l1 = ev[-1], ev[-2], od[-1]
    return float(math.log(l0 / l1)), float(math.log(l0 / l2))


def strip_correlations(L, beta):
    import numpy as np
    K = _check(L, beta)
    n = 1 << L
    s = np.arange(n)
    spin = lambda i: 1 - 2 * ((s >> i) & 1)
    e = np.array([_row_bonds(L, int(x)) for x in s], dtype=float)
    pop = np.array([bin(x).count("1") for x in range(n)])
    diff = pop[s[:, None] ^ s[None, :]]
    T = np.exp(K * ((e[:, None] + e[None, :]) / 2 - L - 2 * diff))     # exponent - 2LK <= 0
    w, V = np.linalg.eigh(T)
    psi, l0 = V[:, -1], w[-1]
    s0, s1 = psi * spin(0), psi * spin(1)
    return (float(np.sum(psi * psi * spin(0) * spin(1))), float(s0 @ T @ s0 / l0),
            float(s0 @ T @ s1 / l0))


__all__ = ["MAX_L", "strip_correlations", "strip_spectrum"]
